export function getHybridBySlug(slug: string): Hybrid | undefined {
  return hybrids.find(h => h.slug === slug)
}

export function getHybridsByZone(zoneId: string): Hybrid[] {
  return hybrids.filter(h => {
    const ids = getZoneIdsByHybridId(h.id)
    return ids.includes(zoneId)
  })
}

export function getFeaturedHybrids(): Hybrid[] {
  return hybrids.filter(h => h.destacado)
}

export function getRelatedHybrids(hybrid: Hybrid): Hybrid[] {
  return hybrid.relacionados
    .map(id => hybrids.find(h => h.id === id))
    .filter((h): h is Hybrid => h !== undefined)
}
